// Find closest Pantone color to a given hex
export function findClosestPantone(hex) {
  const r1 = parseInt(hex.slice(1, 3), 16);
  const g1 = parseInt(hex.slice(3, 5), 16);
  const b1 = parseInt(hex.slice(5, 7), 16);

  let minDist = Infinity;
  let closest = PANTONE_COLORS[0];

  for (const color of PANTONE_COLORS) {
    const r2 = parseInt(color.hex.slice(1, 3), 16);
    const g2 = parseInt(color.hex.slice(3, 5), 16);
    const b2 = parseInt(color.hex.slice(5, 7), 16);

    // Use weighted Euclidean distance in RGB (human perception weights)
    const dr = (r1 - r2) * 0.299;
    const dg = (g1 - g2) * 0.587;
    const db = (b1 - b2) * 0.114;
    const dist = Math.sqrt(dr * dr + dg * dg + db * db);

    if (dist < minDist) {
      minDist = dist;
      closest = color;
    }
  }

  return closest;
}

// Generic color names for when no close Pantone match exists
export function getColorName(hex) {
  const pantone = findClosestPantone(hex);
  if (pantone) return pantone;

  return { hex, name: "Custom Color", pantone: null };
}
